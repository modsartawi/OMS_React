type Dict = { [k: string]: string | Dict }

export function c(key: string, params?: Record<string, unknown>): string {
  let k = key
  if (params && typeof params.count === 'number') k = `${key}_${params.count === 1 ? 'one' : 'other'}`
  const look = (path: string) =>
    path.split('.').reduce<string | Dict | undefined>((o, p) => (typeof o === 'object' ? o[p] : undefined), COPY as Dict)
  let s = look(k)
  if (typeof s !== 'string') s = look(key)
  if (typeof s !== 'string') return key
  return s.replace(/\{\{(\w+)\}\}/g, (_, p: string) => String(params?.[p] ?? ''))
}
