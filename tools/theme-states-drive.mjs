// Manual visual review capture; npm run prototype:theme first.
import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
const { chromium } = createRequire('C:/Playground/frontend/package.json')('playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1600, height: 1200 } })
await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
const checks = [], errors = []
page.on('pageerror', error => errors.push(String(error)))
const check = (name, pass) => { checks.push({ name, pass }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}`) }
const dir = '.issues/assets/356-theme-states'
mkdirSync(dir, { recursive: true })
const shot = name => page.screenshot({ path: `${dir}/${name}.png`, fullPage: true })
try {
 for (const mode of ['light', 'dark']) {
  await page.goto(`http://127.0.0.1:5198/oms/deliveries?variant=selected&review=states&mode=${mode}`)
  await page.getByRole('gridcell', { name: 'COL-00048', exact: true }).waitFor()
  check(`${mode}: compact 28px rows`, await page.locator('.ag-row:not(.ag-row-pinned)').first().evaluate(e => e.getBoundingClientRect().height === 28))
  check(`${mode}: 32px Collection fields`, await page.getByLabel('Business date from', { exact: true }).evaluate(e => e.getBoundingClientRect().height === 32))
  check(`${mode}: pinned totals`, await page.locator('.ag-row-pinned').innerText().then(v => v.includes('13,840.75')))
  await shot(`${mode}-default`)
  await page.getByLabel('Preview ACR scope', { exact: true }).check()
  check(`${mode}: ACR blanks and disables fields`, await page.locator('.state-collection-fields input').evaluateAll(inputs => inputs.length === 7 && inputs.every(e => e.disabled && e.value === '')))
  await page.getByLabel('Preview ACR scope', { exact: true }).uncheck()
  check(`${mode}: scope restores date draft`, await page.getByLabel('Business date from', { exact: true }).inputValue() === '2026-10-01')
  const cell = page.getByRole('gridcell', { name: 'COL-00048', exact: true })
  await cell.dblclick({ position: { x: 38, y: 14 } })
  await page.keyboard.press('Control+c')
  check(`${mode}: native text copying`, (await page.evaluate(() => navigator.clipboard.readText())).length > 0)
  await page.locator('.ag-selection-checkbox input').first().check()
  await cell.click()
  check(`${mode}: focus coexists with selection`, await page.locator('.ag-row-selected .ag-cell-focus').count() > 0)
  await page.keyboard.press('ArrowDown')
  check(`${mode}: arrow stays inside grid`, await page.locator('.ag-cell-focus').getAttribute('col-id') === 'reference' && new URL(page.url()).searchParams.get('variant') === 'selected')
  await cell.click()
  await shot(`${mode}-selected-focus`)
  await page.getByRole('button', { name: 'Secondary action', exact: true }).hover()
  await page.waitForTimeout(250) // Allow the button's 150ms colour transition to finish.
  const buttonHover = await page.getByRole('button', { name: 'Secondary action', exact: true }).evaluate(e => getComputedStyle(e).backgroundColor)
  await page.locator('.ag-row:not(.ag-row-pinned)').nth(1).hover()
  check(`${mode}: shared hover token`, await page.locator('.ag-root-wrapper').evaluate(e => { const css = getComputedStyle(e); return css.getPropertyValue('--ag-row-hover-color').trim() === css.getPropertyValue('--accent').trim() }) && buttonHover !== 'rgba(0, 0, 0, 0)')
  await page.locator('.state-field-samples input').first().focus()
  await page.keyboard.press('Tab')
  check(`${mode}: disabled field skipped by Tab`, await page.locator('input[aria-invalid]').evaluate(e => e === document.activeElement))
  check(`${mode}: visible keyboard focus`, await page.locator('input[aria-invalid]').evaluate(e => getComputedStyle(e).outlineStyle === 'solid'))
  await page.locator('input[aria-invalid]').fill('15.50')
  check(`${mode}: correct amount clears invalid`, await page.locator('input[aria-invalid]').getAttribute('aria-invalid') === 'false')
  await page.locator('input[aria-invalid]').fill('-10')
  const header = page.getByRole('columnheader', { name: 'Amount (SAR)', exact: true })
  await header.locator('.ag-header-cell-label').click()
  check(`${mode}: sortable header`, await header.getAttribute('aria-sort') === 'ascending')
  await page.locator('.ag-floating-filter-button-button:visible').first().click()
  await page.locator('.ag-filter').waitFor()
  check(`${mode}: real filter popup`, await page.locator('.ag-filter').isVisible())
  await shot(`${mode}-filter`)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Loading', exact: true }).click()
  await page.getByText('Loading collections\u2026', { exact: true }).waitFor()
  await shot(`${mode}-loading`)
  await page.getByRole('button', { name: 'Empty', exact: true }).click()
  await page.getByText('No collections match. Adjust the criteria and search again.', { exact: true }).waitFor()
  check(`${mode}: loading and empty visible`, true)
  await shot(`${mode}-empty`)
  await page.getByRole('button', { name: 'Default', exact: true }).click()
  await page.getByLabel('44px two-line rows', { exact: true }).check()
  await page.waitForSelector('.state-store small')
  check(`${mode}: deliberate 44px rows`, await page.locator('.ag-row:not(.ag-row-pinned)').first().evaluate(e => e.getBoundingClientRect().height === 44))
  await page.getByRole('button', { name: 'RTL', exact: true }).click()
  await page.waitForSelector('.ag-rtl')
  check(`${mode}: identity pinned at RTL start`, await page.getByRole('gridcell', { name: 'COL-00048', exact: true }).evaluate(e => e.className.includes('pinned')))
  await shot(`${mode}-rtl-rich`)
  await page.setViewportSize({ width: 1000, height: 850 })
  check(`${mode}: laptop has no page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await shot(`${mode}-laptop`)
  await page.setViewportSize({ width: 600, height: 850 })
  await page.waitForFunction(() => { const box = document.querySelector('#layout-sidebar').getBoundingClientRect(); return box.left >= innerWidth || box.right <= 0 })
  await page.waitForTimeout(250) // Finish the shell's resize transition before capture.
  check(`${mode}: narrow has no page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await shot(`${mode}-narrow`)
  await page.setViewportSize({ width: 1600, height: 1200 })
 }
 check('No browser errors', errors.length === 0)
} finally {
 writeFileSync(`${dir}/verification.json`, JSON.stringify({ checks, errors }, null, 2) + '\n')
 await browser.close()
}
if (checks.some(c => !c.pass)) process.exitCode = 1
