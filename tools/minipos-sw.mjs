// The Mini POS phone app's service worker (BackOffice spec 4063, oms 916), emitted by the build.
//
// The phone app is the second Vite entry (`minipos/index.html`, served at `/minipos/`). Its worker precaches the app
// shell — the entry's HTML, every chunk and stylesheet it reaches, statically or by a dynamic import (the scanner
// library, `@zxing/library`, is one), the manifest and the icons — so the installed app opens with no connection.
// Selling still needs the network: no API call is ever answered from the cache.
//
// Written at build time rather than by hand because the chunk names carry content hashes: the list is read off the
// bundle, and the cache name is derived from it, so a new build installs a new cache and drops the old one.
//
// No dependency (vite-plugin-pwa would bring workbox for one cache list). The pure parts are exported for
// `tools/minipos-sw.test.mjs`.

import { createHash } from 'node:crypto'

/** Where the phone app is served, and its worker's scope. */
export const MINIPOS_BASE = '/minipos/'

/** The `public/minipos/` files the shell needs beside the bundle. */
export const MINIPOS_PUBLIC_FILES = ['manifest.webmanifest', 'icon-192.png', 'icon-512.png', 'icon-512-maskable.png']

const toPosix = (p) => String(p).split('\\').join('/')

/** Whether an output chunk is the phone app's entry: the one whose modules include its main. */
export function isMiniPosEntry(chunk) {
  return chunk.type === 'chunk' && chunk.isEntry && (chunk.moduleIds ?? []).some((id) => toPosix(id).endsWith('/src/app/minipos-main.tsx'))
}

/**
 * Every bundle file the phone app's shell needs, as served paths (`/assets/…`): the entry chunk and every chunk it
 * reaches by a static or a dynamic import, with the stylesheets and assets each of them carries. Nothing of the OMS
 * app that the phone app does not import. Sorted, so the list (and the cache name) is stable across identical builds.
 */
export function shellFiles(bundle, base = '/') {
  const entry = Object.values(bundle).find(isMiniPosEntry)
  if (!entry) return null
  const seen = new Set()
  const files = new Set()
  const visit = (fileName) => {
    if (seen.has(fileName)) return
    seen.add(fileName)
    const chunk = bundle[fileName]
    if (!chunk || chunk.type !== 'chunk') return
    files.add(fileName)
    for (const css of chunk.viteMetadata?.importedCss ?? []) files.add(css)
    for (const asset of chunk.viteMetadata?.importedAssets ?? []) files.add(asset)
    for (const next of [...(chunk.imports ?? []), ...(chunk.dynamicImports ?? [])]) visit(next)
  }
  visit(entry.fileName)
  return [...files].sort().map((f) => base + f)
}

/** The worker's source: precache `shell` under a cache named for its contents; serve it cache-first. */
export function serviceWorkerSource(shell) {
  const version = createHash('sha256').update(shell.join('\n')).digest('hex').slice(0, 12)
  return `// Mini POS service worker (oms 916) - generated by tools/minipos-sw.mjs at build time. Do not edit.
const CACHE = 'minipos-${version}'
const BASE = '${MINIPOS_BASE}'
const SHELL = ${JSON.stringify(shell, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(SHELL)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('minipos-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return
  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return
  // The app's page: the network's when there is one (a new build), else the cached shell.
  if (request.mode === 'navigate' && url.pathname.startsWith(BASE)) {
    event.respondWith(fetch(request).catch(() => caches.match(BASE + 'index.html')))
    return
  }
  // The shell's files: cached. Everything else (every API call) goes to the network, untouched.
  if (SHELL.includes(url.pathname)) {
    event.respondWith(caches.match(request).then((hit) => hit || fetch(request)))
  }
})
`
}

/** The Vite plugin: emits `minipos/sw.js` beside `minipos/index.html` in a build that has the phone app's entry. */
export function miniPosServiceWorker() {
  return {
    name: 'minipos-service-worker',
    apply: 'build',
    enforce: 'post',
    generateBundle(_options, bundle) {
      const files = shellFiles(bundle)
      if (!files) return // a build without the phone app's entry (a gate's partial build)
      const shell = [
        MINIPOS_BASE,
        MINIPOS_BASE + 'index.html',
        ...MINIPOS_PUBLIC_FILES.map((f) => MINIPOS_BASE + f),
        ...files,
      ]
      this.emitFile({ type: 'asset', fileName: 'minipos/sw.js', source: serviceWorkerSource(shell) })
    },
  }
}
