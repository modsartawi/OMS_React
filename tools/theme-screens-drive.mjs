import { createRequire } from 'node:module'
import { mkdirSync, writeFileSync } from 'node:fs'
const {chromium}=createRequire('C:/Playground/frontend/package.json')('playwright')
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1600,height:1100}})
await page.context().grantPermissions(['clipboard-read','clipboard-write'])
const errors=[], checks=[]
page.on('pageerror',e=>errors.push(String(e)))
const check=(name,pass)=>{checks.push({name,pass});console.log(`${pass?'PASS':'FAIL'} ${name}`)}
const dir='.issues/assets/356-theme-screens'
mkdirSync(dir,{recursive:true})
const base='http://127.0.0.1:5198'
const shot=async name=>page.screenshot({path:`${dir}/${name}.png`,fullPage:true})
for(const mode of ['light','dark']) {
 await page.goto(`${base}/oms/delivery/8000048?variant=selected&mode=${mode}`)
 await page.getByRole('gridcell',{name:'200706',exact:true}).waitFor()
 check(`${mode}: fictional delivery`,await page.getByLabel('Document identity').innerText().then(text=>text.includes('8000048')&&text.includes('Reem Al-Harbi')))
 const cell=page.getByRole('gridcell',{name:'200706',exact:true})
 await cell.dblclick({position:{x:25,y:14}});await page.keyboard.press('Control+c')
 check(`${mode}: copy item number`,await page.evaluate(()=>navigator.clipboard.readText())==='200706')
 await shot(`delivery-${mode}`)
 for(const tab of ['Header Conditions','Log','Jobs','Items']) {
  await page.getByRole('tab',{name:new RegExp(`^${tab}`)}).click()
  check(`${mode}: ${tab} tab`,await page.locator('[role=tabpanel]:not([hidden]) .ag-row').count()>0)
 }
 await page.locator('summary').filter({hasText:'All statuses'}).click()
 check(`${mode}: status disclosure`,await page.locator('details[open]').count()===1)
 await page.getByRole('button',{name:/^Add Note/}).click()
 await page.getByRole('dialog').waitFor()
 check(`${mode}: note dialog`,await page.getByRole('dialog').isVisible())
 await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click()
 await page.getByRole('button',{name:'RTL',exact:true}).click()
 await page.waitForSelector('.ag-rtl')
 check(`${mode}: RTL grid`,await page.locator('.ag-rtl').count()>0)
 await shot(`delivery-${mode}-rtl`)
 await page.getByRole('navigation',{name:'Theme preview screens'}).getByRole('link',{name:'POS simulation'}).click()
 await page.getByRole('button',{name:/Process/}).waitFor()
 check(`${mode}: navigation keeps theme`,new URL(page.url()).searchParams.get('mode')===mode)
 await page.getByRole('button',{name:'RTL',exact:true}).click()
 for(const scenario of ['fired','near','plain','trace']) {
  await page.getByLabel('Sample basket').selectOption(scenario)
  await page.getByRole('button',{name:/Process/}).click()
  await page.locator('[data-work-area="results"]').waitFor()
  check(`${mode}: ${scenario} replay`,await page.locator('[data-result-line]').count()>0)
  const row=page.locator('[data-result-line]').first()
  await row.click()
  check(`${mode}: ${scenario} expansion`,await row.getAttribute('aria-expanded')==='true')
  await shot(`simulation-${mode}-${scenario}`)
 }
}
// Edit and replay: mark stale, then explicitly refuse unsupported calculations.
await page.getByLabel('Sample basket').selectOption('fired')
await page.getByRole('button',{name:/Process/}).click()
await page.locator('[data-work-area="results"]').waitFor()
const quantity=page.locator('input[type=number]').first()
await quantity.fill('9')
check('Editing marks results stale',(await page.locator('main').innerText()).includes('Inputs changed'))
await page.getByRole('button',{name:/Process/}).click()
await page.getByText(/This preview replays captured baskets only/).waitFor()
check('Edited basket is not mispriced',await page.getByText(/This preview replays captured baskets only/).isVisible())
await page.getByRole('button',{name:'Reset sample'}).click()
await page.keyboard.press('Control+Enter')
await page.locator('[data-work-area="results"]').waitFor()
check('Reset and keyboard Process work',await page.locator('[data-result-line]').count()===1)
await page.getByRole('button',{name:'RTL',exact:true}).click()
check('Simulation supports RTL',await page.evaluate(()=>document.documentElement.dir==='rtl'))
await shot('simulation-dark-rtl')
await page.setViewportSize({width:1100,height:850})
await shot('simulation-laptop')
check('Laptop page stays within viewport',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
await page.getByRole('navigation',{name:'Theme preview screens'}).getByRole('link',{name:'Delivery inquiry'}).click()
await page.waitForSelector('.ag-row')
await page.getByRole('gridcell',{name:'8000048',exact:true}).click()
await page.getByRole('button',{name:'Preview delivery'}).click()
await page.getByLabel('Document identity').waitFor()
check('Open selected enters full delivery detail',page.url().includes('/oms/delivery/8000048?'))
await page.getByRole('link',{name:'Back to Delivery Documents'}).click()
await page.waitForSelector('.prototype-command-strip')
check('Detail back returns to selected inquiry',page.url().includes('variant=selected'))
check('No browser errors',errors.length===0)
writeFileSync(`${dir}/verification.json`,JSON.stringify({checks,errors},null,2)+'\n')
await browser.close()
if(checks.some(c=>!c.pass)) process.exitCode=1
